#!/usr/bin/env node
/**
 * Regenerates the dark palette in src/app/globals.css — everything between
 * `/* dark-palette:start *\/` and `/* dark-palette:end *\/`.
 *
 * Dark mode inverts each colour scale (50 <-> 950, 100 <-> 900, ...), so every
 * utility follows without a `dark:` class. The values come from Tailwind's own
 * theme plus the families this app defines in globals.css (`sand`, `brand`),
 * and only families the source actually uses are written, so the block cannot
 * silently go stale when a colour family comes into or out of use.
 *
 *   node scripts/generate-dark-palette.mjs
 *
 * Running it twice must leave the file unchanged.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const CSS_PATH = join(ROOT, "src/app/globals.css");
const THEME_PATH = join(ROOT, "node_modules/tailwindcss/theme.css");
const START = "/* dark-palette:start */";
const END = "/* dark-palette:end */";

/** The neutral family: its dark end becomes the surface that `white` maps to. */
const NEUTRAL = "sand";
const SHADES = ["50", "100", "200", "300", "400", "600", "700", "800", "900", "950"];
const MIRROR = {
  50: "950", 100: "900", 200: "800", 300: "700", 400: "600",
  600: "400", 700: "300", 800: "200", 900: "100", 950: "50",
};

function readPalette(css) {
  const palette = new Map();
  for (const match of css.matchAll(/--color-([a-z]+)-(\d{2,3}):\s*([^;]+);/g)) {
    const [, family, shade, value] = match;
    if (!palette.has(family)) palette.set(family, {});
    palette.get(family)[shade] = value.trim();
  }
  return palette;
}

function sourceText(dir) {
  let text = "";
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (name === "generated" || path === CSS_PATH) continue;
    if (statSync(path).isDirectory()) text += sourceText(path);
    else if (/\.(tsx?|css)$/.test(name)) text += readFileSync(path, "utf8");
  }
  return text;
}

function parseOklch(value) {
  const match = /oklch\(([\d.]+)% ([\d.]+) ([\d.]+)\)/.exec(value);
  if (!match) throw new Error(`Not an oklch() colour: ${value}`);
  return match.slice(1).map(Number);
}

/** Halfway between the neutral's 900 and 950: one step above the dark page. */
function darkSurface(neutral) {
  const [a, b] = [parseOklch(neutral["900"]), parseOklch(neutral["950"])];
  const mid = a.map((value, index) => (value + b[index]) / 2);
  const round = (value, places) => Number(value.toFixed(places));
  return `oklch(${round(mid[0], 1)}% ${round(mid[1], 3)} ${round(mid[2], 3)})`;
}

const css = readFileSync(CSS_PATH, "utf8");
const startAt = css.indexOf(START);
const endAt = css.indexOf(END);
if (startAt < 0 || endAt < startAt) throw new Error("dark-palette markers not found");

// The app's own families are declared outside the generated block.
const own = readPalette(css.slice(0, startAt) + css.slice(endAt));
const tailwind = readPalette(readFileSync(THEME_PATH, "utf8"));
const used = sourceText(join(ROOT, "src"));
const families = [...own.keys(), ...[...tailwind.keys()].filter((name) => !own.has(name))]
  .filter((family) => new RegExp(`-${family}-\\d`).test(used));

const lines = [];
for (const family of families) {
  const scale = own.get(family) ?? tailwind.get(family);
  for (const shade of SHADES) {
    const value = scale[MIRROR[shade]];
    if (!value) throw new Error(`${family}-${MIRROR[shade]} is not defined`);
    lines.push(`    --color-${family}-${shade}: ${value};`);
  }
}
lines.push(`    --color-white: ${darkSurface(own.get(NEUTRAL))};`);
const declarations = lines.join("\n");

const block = `${START}
/*
 * Dark mode by remapping the palette, not by \`dark:\` variants.
 *
 * Every utility in this app reads its colour from a \`--color-*\` variable, so
 * inverting each scale (50 <-> 950, 100 <-> 900, ...) turns the whole UI dark
 * without touching a class list — and a component added later is dark-ready by
 * default instead of needing a second set of classes to be remembered. White,
 * which cards and inputs use, becomes a surface one step above the page so
 * \`${NEUTRAL}-100\` hovers stay visible on it. Black is left alone so dialog
 * backdrops still darken.
 *
 * GENERATED by scripts/generate-dark-palette.mjs from Tailwind's theme and the
 * families declared above — rerun it rather than editing this block. Applies
 * when the OS prefers dark unless the viewer chose light, or whenever they
 * chose dark — on screen only, so a printed or saved-as-PDF page is always
 * dark text on white paper.
 */
@media screen and (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${declarations}
  }
}

@media screen {
  :root[data-theme="dark"] {
    color-scheme: dark;
${declarations}
  }
}
`;

const next = css.slice(0, startAt) + block + css.slice(endAt);
if (next !== css) writeFileSync(CSS_PATH, next);
console.log(`dark palette: ${families.join(", ")}${next === css ? " (unchanged)" : ""}`);
